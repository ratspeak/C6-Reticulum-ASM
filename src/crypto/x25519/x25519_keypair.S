# ============================================================================
# @function:    x25519_keypair
# @module:      crypto/x25519
# @inputs:      a0 = pk_out ptr (32 bytes; canonical wire u-coordinate of pk)
#               a1 = sk_out ptr (32 bytes; raw private key)
# @outputs:     sk_out filled with 32 bytes from rng_bytes (the raw private
#                      scalar — clamping is applied internally by
#                      x25519_scalar_mult on a private copy, per RFC 7748
#                      §6.1 convention that callers store the un-clamped
#                      bytes as the private key).
#               pk_out = X25519(sk_out, base_point=9), the canonical
#                       32-byte LE encoding of pk's u-coordinate.
# @clobbers:    t0..t6, a2..a7, s0, s1
# @preserves:   sp, gp, ra, all other callee-saved
# @stack:       16
# @cycles:      bounded (≈ rng_bytes(32) + scalar_mult ≈ 4 × 10^6)
# @ct:          required
# @spec:        RFC 7748 §6.1: an X25519 keypair is generated by
#               drawing 32 random bytes for the private key and
#               computing the public key as the base-point scalar
#               product. Per ADR / milestone-2 §rng, on QEMU bring-up
#               the entropy source is the deterministic-fake RNG; the
#               production ESP32-C6 build replaces rng_bytes with the
#               on-chip TRNG-seeded CSPRNG.
# @verify:      proofs/crypto/x25519/X25519.cry, proofs/crypto/x25519/x25519_keypair.saw
# @tests:       tests/crypto/x25519/test_x25519_keypair.py
#               (Tier C bridge: drives the asm under qemu-system-riscv32
#               with the deterministic-fake RNG; the test computes the
#               expected sk_out from the rng oracle and the expected
#               pk_out via Python's pyca/cryptography X25519 against
#               that sk_out, and asserts byte-for-byte equality.)
# @adrs:        0001, 0002, 0006, 0009
# @status:      verified
# ============================================================================

        .include "x25519.S"

        .equ FRAME,    16
        .equ RA_OFF,   12
        .equ S0_OFF,    8       /* pk_out                                 */
        .equ S1_OFF,    4       /* sk_out                                 */

        .section .text.x25519_keypair, "ax", @progbits
        .global x25519_keypair
        .type   x25519_keypair, @function
x25519_keypair:
        addi    sp, sp, -FRAME
        sw      ra, RA_OFF(sp)
        sw      s0, S0_OFF(sp)
        sw      s1, S1_OFF(sp)
        mv      s0, a0                          /* pk_out                 */
        mv      s1, a1                          /* sk_out                 */

        # sk_out := 32 bytes from the RNG.
        mv      a0, s1
        li      a1, 32
        call    rng_bytes

        # pk_out := X25519(sk_out, base_point=9).
        mv      a0, s0
        mv      a1, s1
        la      a2, x25519_base_point
        call    x25519_scalar_mult

        lw      s1, S1_OFF(sp)
        lw      s0, S0_OFF(sp)
        lw      ra, RA_OFF(sp)
        addi    sp, sp, FRAME
        ret

        .size   x25519_keypair, . - x25519_keypair
